def test_dry_run_preflight_lists_sources_without_writing_output(tmp_path: Path) -> None:
    repository = tmp_path / "repo"
    build = repository / "build_linux"
    source = repository / "src" / "main.cpp"
    build.mkdir(parents=True)
    source.parent.mkdir(parents=True)
    source.write_text("int main() { return 0; }\n", encoding="utf-8")
    (build / "compile_commands.json").write_text(json.dumps([{
        "directory": str(repository), "file": str(source), "arguments": ["clang++", "-std=c++17", "-c", str(source)]
    }]), encoding="utf-8")
    output = tmp_path / "output" / "extract"
    api_config = ROOT / "thread_api_config.json"
    command = [
        sys.executable, str(ROOT / "extract_repository_graph_rca_v2.py"),
        "--repository-root", str(repository), "--build-directory", str(build),
        "--output-directory", str(output), "--libclang", "not-needed-for-dry-run.so",
        "--thread-api-config", str(api_config), "--dry-run",
    ]
    result = subprocess.run(command, capture_output=True, text=True)
    assert result.returncode == 0, result.stdout + result.stderr
    assert "Preflight OK: 1 source translation units available; 1 selected" in result.stdout
    assert "src/main.cpp" in result.stdout
    assert "no AST was parsed" in result.stdout
    assert not output.exists()


