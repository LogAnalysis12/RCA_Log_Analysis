    artifacts["lock_usage"].append({"function_id": "f1", "function_name": "Ledger::audit", "mutex_text": "Ledger::m_mutex", "event": "RAII_ACQUIRE_AND_SCOPE_RELEASE", "line": "15", "relative_path": "src/ledger.cpp"})
