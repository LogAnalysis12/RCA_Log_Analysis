    cp_dir = tmp_path / "checkpoints"
    output_dir = tmp_path / "out"
    cp_dir.mkdir()
    checkpoint = {
        "extractor_version": "rca-v2.0",
        "relative_path": "src/example.cpp",
        "status": "SUCCESS",
        "duration_seconds": 0.1,
        "functions": [{"function_id": "fn1", "qualified_name": "Example::run", "relative_path": "src/example.cpp", "start_line": 1, "end_line": 5, "source_code": "void Example::run() {}"}],
        "calls": [{"caller_function_id": "fn1", "callee_function_id": "fn2", "callee_name": "helper", "qualified_callee_name": "Example::helper", "callee_signature": "void()", "call_line": 2, "call_column": 3, "call_type": "DIRECT", "resolution_status": "RESOLVED_PROJECT", "call_expression": "helper()"}],
        "data_fields": [{"field_id": "fld1", "repository_id": "Example", "field_name": "value", "qualified_name": "Example::value", "field_type": "int", "declaration_relative_path": "src/example.cpp", "declaration_line": 3, "declaration_kind": "FIELD"}],
        "data_accesses": [{"function_id": "fn1", "field_id": "fld1", "chain": "value", "suffix2": "value", "field_name": "value", "field_type": "int", "access_type": "READ", "line": 4, "column": 5}],
        "diagnostic_summary": {},
        "worker_exit_code": 0,
    }
    for key in [
        "variables", "function_parameters", "variable_accesses", "call_arguments", "data_flows", "lifetime_events", "thread_spawns", "lock_usage", "pointer_events", "synchronization_events", "control_flow_events", "macro_events", "types", "type_relationships", "callable_targets", "callable_calls", "return_flows", "call_sites", "external_symbols", "function_return_types",
    ]:
        checkpoint[key] = []
    checkpoint["call_sites"] = [{"call_site_id": "site1", "caller_function_id": "fn1", "callee_node_id": "ext1", "callee_name": "external_api", "relative_path": "src/example.cpp", "line": 5, "column": 1, "resolution_status": "RESOLVED_EXTERNAL", "evidence_grade": "STATIC_AST_CALL_SITE"}]
    checkpoint["external_symbols"] = [{"symbol_id": "ext1", "qualified_name": "external_api", "signature": "void()", "declaration_file": "/usr/include/example.h"}]
