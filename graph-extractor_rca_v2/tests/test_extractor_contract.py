def test_smart_pointer_aliases_use_canonical_type_spelling() -> None:
    """Regression test for aliases such as `using Owner = std::shared_ptr<Foo>`."""
    import types
    from enum import Enum

    source = (ROOT / "extract_graph_rca_v2.py").read_text(encoding="utf-8")
    kind_names = sorted(set(re.findall(r"cindex\.CursorKind\.([A-Z_0-9]+)", (ROOT / "extract_graph_step3_fields_working.py").read_text(encoding="utf-8"))))
    cursor_kind = Enum("CursorKind", {name: name for name in kind_names})
    fake_cindex = types.ModuleType("clang.cindex")
    fake_cindex.CursorKind = cursor_kind
    fake_clang = types.ModuleType("clang")
    fake_clang.cindex = fake_cindex

    saved_clang = sys.modules.get("clang")
    saved_cindex = sys.modules.get("clang.cindex")
    saved_base = sys.modules.pop("extract_graph_step3_fields_working", None)
    sys.modules["clang"] = fake_clang
    sys.modules["clang.cindex"] = fake_cindex
    try:
        spec = importlib.util.spec_from_file_location("rca_extractor_alias_test", ROOT / "extract_graph_rca_v2.py")
        assert spec and spec.loader
        module = importlib.util.module_from_spec(spec)
        sys.modules[spec.name] = module
        spec.loader.exec_module(module)

        class CanonicalType:
            spelling = "std::shared_ptr<Foo>"
            kind = types.SimpleNamespace(name="RECORD")

            def get_canonical(self):
                return self

        class FakeType:
            spelling = "Owner"
            kind = types.SimpleNamespace(name="ELABORATED")

            def get_canonical(self):
                return CanonicalType()

            def is_const_qualified(self):
                return False

            def is_volatile_qualified(self):
                return False

        alias_use = types.SimpleNamespace(type=FakeType(), spelling="Owner")
        config = json.loads((ROOT / "thread_api_config.json").read_text(encoding="utf-8"))
        props = module._type_properties(alias_use, config)
        assert props["smart_pointer_kind"] == "SHARED_PTR"
        assert props["is_pointer_like"] is True
        assert props["ownership_model_hint"] == "SHARED_OWNERSHIP"
    finally:
        sys.modules.pop("rca_extractor_alias_test", None)
        sys.modules.pop("extract_graph_step3_fields_working", None)
        if saved_base is not None:
            sys.modules["extract_graph_step3_fields_working"] = saved_base
        if saved_clang is not None:
            sys.modules["clang"] = saved_clang
        else:
            sys.modules.pop("clang", None)
        if saved_cindex is not None:
            sys.modules["clang.cindex"] = saved_cindex
        else:
            sys.modules.pop("clang.cindex", None)


def test_artifact_validator_accepts_empty_complete_contract(tmp_path: Path) -> None:
    # Empty-but-schema-complete artifacts are valid if the manifest truthfully says
    # that every selected TU was processed and none failed.
    sys.path.insert(0, str(ROOT))
    from tools.validate_extraction_artifacts import LEGACY_CSV_HEADERS, validate

    out = tmp_path / "out"
    out.mkdir()
    for filename, header in {**LEGACY_CSV_HEADERS, **runner.EXTRA_CSV_FIELDS}.items():
        write_csv(out / filename, header, [])
    (out / "functions.jsonl").write_text("", encoding="utf-8")
    (out / "callable_targets.jsonl").write_text("", encoding="utf-8")
    (out / "external_symbols.jsonl").write_text("", encoding="utf-8")
    (out / "manifest.json").write_text(json.dumps({
        "legacy_artifacts_compatible": True, "static_evidence_only": True,
        "is_partial_run": False, "available_translation_units": 0, "selected_translation_units": 0,
    }), encoding="utf-8")
    (out / "extraction_report.json").write_text(json.dumps({
        "translation_units_recorded": 0, "translation_units_successful": 0,
        "translation_units_failed": 0, "available_translation_units": 0,
        "selected_translation_units": 0,
    }), encoding="utf-8")
    result = validate(out, require_complete=True)
    assert result["status"] == "PASS", result["errors"]
    assert result["warnings"] == []
    assert result["ground_truth_was_read"] is False
    assert result["neo4j_was_written"] is False
